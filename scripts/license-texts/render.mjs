/**
 * Renders `THIRD-PARTY-NOTICES.md` from the data `scripts/licenses.mjs`
 * collects (the same data the app's licences view reads).
 */

/** A Markdown table cell. */
function cell(text) {
  return text.replaceAll("|", "\\|");
}

/** A fence that no line of `text` can close early. */
function fence(text) {
  const longest = Math.max(3, ...[...text.matchAll(/`+/g)].map((match) => match[0].length + 1));
  return "`".repeat(longest);
}

/** Renders THIRD-PARTY-NOTICES.md; `repository` is blurrd's repository URL. */
export function renderNotices(data, repository) {
  const KINDS = [
    ["binary", "Bundled programs", "Component"],
    ["model", "OCR models", "File"],
    ["crate", "Rust crates", "Crate"],
    ["npm", "npm packages", "Package"],
  ];
  const lines = [
    "# Third-party notices",
    "",
    "blurrd includes the third-party software listed below. Each component is",
    "used under its licence; the full licence texts follow the lists. The app",
    "shows the same information under About > Open-source licenses.",
    "",
    "This file is generated by `pnpm notices` (`scripts/licenses.mjs`); do not",
    "edit it by hand. blurrd itself is licensed under the GNU General Public",
    "License 3.0 only with additional terms (author attribution, linking",
    `permission; see \`LICENSE\` and \`NOTICE\`, ${repository}).`,
    "",
    "The app ships no font files: it uses the operating system's interface",
    "and monospace fonts.",
  ];
  for (const [kind, title, column] of KINDS) {
    const items = data.packages.filter((item) => item.kind === kind);
    if (items.length === 0) continue;
    lines.push("", `## ${title} (${items.length})`, "");
    lines.push(`| ${column} | Version | Licence | Licence texts |`, "| --- | --- | --- | --- |");
    for (const item of items) {
      const texts = item.texts.map((index) => `[${index + 1}](#licence-${index + 1})`).join(", ");
      lines.push(
        `| [${cell(item.name)}](${item.url}) | ${cell(item.version)} | ${cell(item.license)} | ${texts} |`,
      );
    }
    for (const item of items.filter((entry) => entry.note || entry.source)) {
      lines.push("", `**${item.name} ${item.version}:** ${item.note ?? ""}`.trimEnd());
      if (item.source) lines.push(`Corresponding source: <${item.source}>`);
    }
  }
  lines.push("", "## Licence texts");
  data.texts.forEach((entry, index) => {
    const users = data.packages
      .filter((item) => item.texts.includes(index))
      .map((item) => `${item.name} ${item.version}`);
    const marker = fence(entry.text);
    lines.push(
      "",
      `<a id="licence-${index + 1}"></a>`,
      "",
      `### ${index + 1}. ${entry.license}`,
      "",
      `Used by: ${users.join(", ")}`,
      "",
      `${marker}text`,
      entry.text,
      marker,
    );
  });
  return `${lines.join("\n")}\n`;
}
